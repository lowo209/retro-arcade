import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createGateway, DEFAULT_ORIGINS } from './r2-gateway.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function buildR2Gateway({ root = ROOT, releaseDirectory = '.local/r2-release' } = {}) {
  const release = path.resolve(root, releaseDirectory);
  if (!release.startsWith(path.resolve(root, '.local') + path.sep)) throw new Error('Gateway output must remain in the local release directory.');
  const plan = JSON.parse(fs.readFileSync(path.join(release, 'upload-plan.json'), 'utf8'));
  if (plan.schema !== 1 || !Array.isArray(plan.files)) throw new Error('Prepare a valid R2 upload plan first.');
  const objects = plan.files.map(value => ({ key: value.key, bytes: value.bytes, contentType: value.contentType, etag: value.etag }))
    .sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0);
  const totalBytes = objects.reduce((sum, value) => sum + value.bytes, 0);
  if (!Number.isSafeInteger(totalBytes) || totalBytes !== plan.totalBytes || totalBytes > 9_000_000_000) throw new Error('Gateway release exceeds the 9 GB storage budget or its plan is incomplete.');
  const config = { prefix: plan.prefix, allowedOrigins: DEFAULT_ORIGINS, objects };
  createGateway(config); // Validate all public keys and headers before generating.
  const template = fs.readFileSync(path.join(root, 'scripts/r2-gateway.mjs'), 'utf8');
  if (/^\s*import\b/m.test(template)) throw new Error('Gateway template must be self-contained.');
  const worker = '// Generated by scripts/build-r2-gateway.mjs. Keep Workers Free and observability disabled.\n'
    + template.replace(/^export (const|function) /gm, '$1 ')
    + '\nexport default createGateway(' + JSON.stringify(config) + ');\n';
  const bytes = Buffer.byteLength(worker, 'utf8');
  if (bytes > 65_536) throw new Error('Gateway script exceeds its reviewed 64 KiB budget.');
  const output = path.join(release, 'gateway-worker.mjs');
  fs.writeFileSync(output, worker);
  return { output, bytes, objects: objects.length, totalBytes, prefix: plan.prefix };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(buildR2Gateway());
